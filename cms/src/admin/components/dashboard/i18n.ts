/** Plural bucket: Serbian (`me`) has 1 / 2–4 / 5+ forms, Albanian and English 1 / many. */
export function pluralKey(lang: Lang, n: number): '1' | '2' | '5' {
  if (lang !== 'me') return n === 1 ? '1' : '5';
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return '1';
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return '2';
  return '5';
}

/** First letter upper-case (Intl weekday/month names are lower-case in SR/SQ). */
export const capitalize = (s: string) => (s ? s[0].toLocaleUpperCase() + s.slice(1) : s);
